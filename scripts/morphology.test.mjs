#!/usr/bin/env node
// Проверка правил словоизменения на заведомо известных парах.
// Запуск: npm run test:morph

import {
  adjectiveForms, conjugatePresent, countSyllables, declineNoun,
  feminineAccusativeArticle, fixAccentPosition, pluralForm, shiftAccentForward,
} from './morphology.mjs';

let failed = 0;
let passed = 0;

function eq(actual, expected, what) {
  const a = Array.isArray(actual) ? actual.join(' ') : String(actual);
  const e = Array.isArray(expected) ? expected.join(' ') : String(expected);
  if (a === e) { passed++; return; }
  failed++;
  console.error(`  ✗ ${what}\n      получено: ${a}\n      ожидалось: ${e}`);
}

// ─── Слоги ────────────────────────────────────────────────────────────────
console.log('Слоги');
for (const [word, n] of [
  ['σπίτι', 2], ['άνθρωπος', 3], ['παιδί', 2], ['ουρανός', 3],
  ['καφές', 2], ['μάθημα', 3], ['ευχαριστώ', 4],
]) eq(countSyllables(word), n, `слогов в ${word}`);

// ─── Сдвиг ударения ───────────────────────────────────────────────────────
console.log('Сдвиг ударения');
eq(fixAccentPosition('μάθηματα'), 'μαθήματα', 'μάθηματα → μαθήματα');
eq(fixAccentPosition('πρόβληματα'), 'προβλήματα', 'πρόβληματα → προβλήματα');
eq(fixAccentPosition('άνθρωποι'), 'άνθρωποι', 'άνθρωποι не сдвигается');
eq(fixAccentPosition('παράθυρα'), 'παράθυρα', 'παράθυρα не сдвигается');

// ─── Глаголы ──────────────────────────────────────────────────────────────
console.log('Глаголы');
eq(conjugatePresent('γράφω').forms,
  ['γράφω', 'γράφεις', 'γράφει', 'γράφουμε', 'γράφετε', 'γράφουν'], 'γράφω');
eq(conjugatePresent('διαβάζω').forms,
  ['διαβάζω', 'διαβάζεις', 'διαβάζει', 'διαβάζουμε', 'διαβάζετε', 'διαβάζουν'], 'διαβάζω');
eq(conjugatePresent('καταλαβαίνω').forms,
  ['καταλαβαίνω', 'καταλαβαίνεις', 'καταλαβαίνει', 'καταλαβαίνουμε', 'καταλαβαίνετε', 'καταλαβαίνουν'],
  'καταλαβαίνω');
eq(conjugatePresent('μιλάω').forms,
  ['μιλάω', 'μιλάς', 'μιλάει', 'μιλάμε', 'μιλάτε', 'μιλάνε'], 'μιλάω');
eq(conjugatePresent('αγαπάω').forms,
  ['αγαπάω', 'αγαπάς', 'αγαπάει', 'αγαπάμε', 'αγαπάτε', 'αγαπάνε'], 'αγαπάω');
eq(!!conjugatePresent('μπορώ').skip, true, 'μπορώ — отказ, спряжение неоднозначно');
eq(!!conjugatePresent('είμαι').skip, true, 'είμαι — отказ, среднепассивный');
eq(!!conjugatePresent('κοιμάμαι').skip, true, 'κοιμάμαι — отказ, среднепассивный');

// ─── Прилагательные ───────────────────────────────────────────────────────
console.log('Прилагательные');
for (const [m, f, n] of [
  ['μεγάλος', 'μεγάλη', 'μεγάλο'],
  ['μικρός', 'μικρή', 'μικρό'],
  ['καλός', 'καλή', 'καλό'],
  ['κακός', 'κακή', 'κακό'],
  ['ωραίος', 'ωραία', 'ωραίο'],
  ['καινούργιος', 'καινούργια', 'καινούργιο'],
  ['παλιός', 'παλιά', 'παλιό'],
  ['ακριβός', 'ακριβή', 'ακριβό'],
  ['φθηνός', 'φθηνή', 'φθηνό'],
  ['εύκολος', 'εύκολη', 'εύκολο'],
  ['δύσκολος', 'δύσκολη', 'δύσκολο'],
  ['ανοιχτός', 'ανοιχτή', 'ανοιχτό'],
  ['κλειστός', 'κλειστή', 'κλειστό'],
  ['νέος', 'νέα', 'νέο'],
  ['όμορφος', 'όμορφη', 'όμορφο'],
  ['πλούσιος', 'πλούσια', 'πλούσιο'],
  ['ελληνικός', 'ελληνική', 'ελληνικό'],
]) eq(adjectiveForms(m).forms, [m, f, n], m);

// ─── Существительные ──────────────────────────────────────────────────────
console.log('Существительные');
for (const [art, sg, pl] of [
  ['το', 'σπίτι', 'σπίτια'],
  ['το', 'τραπέζι', 'τραπέζια'],
  ['το', 'κρεβάτι', 'κρεβάτια'],
  ['το', 'κλειδί', 'κλειδιά'],
  ['το', 'ψωμί', 'ψωμιά'],
  ['το', 'παιδί', 'παιδιά'],
  ['το', 'παράθυρο', 'παράθυρα'],
  ['το', 'βιβλίο', 'βιβλία'],
  ['το', 'ψυγείο', 'ψυγεία'],
  ['το', 'δωμάτιο', 'δωμάτια'],
  ['το', 'μάθημα', 'μαθήματα'],
  ['το', 'πρόβλημα', 'προβλήματα'],
  ['η', 'πόρτα', 'πόρτες'],
  ['η', 'καρέκλα', 'καρέκλες'],
  ['η', 'κουζίνα', 'κουζίνες'],
  ['η', 'γυναίκα', 'γυναίκες'],
  ['ο', 'άνθρωπος', 'άνθρωποι'],
  ['ο', 'δρόμος', 'δρόμοι'],
  ['ο', 'καφές', 'καφέδες'],
  ['ο', 'καναπές', 'καναπέδες'],
  ['ο', 'πατέρας', 'πατέρες'],
  ['ο', 'άντρας', 'άντρες'],
  ['ο', 'μαθητής', 'μαθητές'],
  ['ο', 'ναύτης', 'ναύτες'],
  // Ударные окончания сохраняют ударение на окончании
  ['το', 'βουνό', 'βουνά'],
  ['το', 'νερό', 'νερά'],
  ['η', 'καρδιά', 'καρδιές'],
  ['η', 'ζωή', 'ζωές'],
  ['η', 'αδερφή', 'αδερφές'],
  ['ο', 'γιατρός', 'γιατροί'],
  ['ο', 'αδερφός', 'αδερφοί'],
  ['ο', 'λαός', 'λαοί'],
]) {
  const r = pluralForm(sg, art);
  eq(r.plural ?? `отказ: ${r.skip}`, pl, `${art} ${sg}`);
}

console.log('Отказы там, где правило неприменимо');
eq(!!pluralForm('πόλη', 'η').skip, true, 'η πόλη — отказ, -η неоднозначно');
eq(!!pluralForm('γράψιμο', 'το').skip, true, 'το γράψιμο — отказ');

// Правила читают конец строки и правят ударение в ней же — на словосочетании
// это давало «τα εμπορικό κέντρα» (определение не согласовано) и
// «οι μουσικη τεχνολόγίες» (ударение уехало через всю строку).
// Согласование частей правилами не описано, поэтому здесь нужен отказ,
// а не выведенная форма: пустая клетка просто не спросится.
console.log('Словосочетания правилам не по зубам — нужен отказ');
for (const [art, phrase] of [
  ['το', 'εμπορικό κέντρο'], ['η', 'παιδική χαρά'], ['η', 'μουσική τεχνολογία'],
  ['η', 'Ευρωπαϊκή Ένωση'], ['το', 'χαρτί υγείας'], ['το', 'σούπερ μάρκετ'],
]) {
  eq(!!pluralForm(phrase, art).skip, true, `${art} ${phrase} — отказ во мн. числе`);
  eq(!!declineNoun(phrase, art).skip, true, `${art} ${phrase} — отказ в склонении`);
}
eq(!!conjugatePresent('κάνω μπάνιο').skip, true, 'κάνω μπάνιο — отказ в спряжении');
eq(!!adjectiveForms('πολύ ωραίος').skip, true, 'πολύ ωραίος — отказ в родах');

// Род при отказе всё равно известен — он из артикля, а не из окончания.
// Без него сборка не может подставить артикли к формам, вписанным руками.
eq(declineNoun('εμπορικό κέντρο', 'το').gender, 'n', 'το εμπορικό κέντρο — род при отказе');
eq(declineNoun('παιδική χαρά', 'η').gender, 'f', 'η παιδική χαρά — род при отказе');

// ─── Синизиса ─────────────────────────────────────────────────────────────
console.log('Синизиса (безударная ι перед гласной слога не даёт)');
for (const [word, n] of [
  ['πιάτο', 2], ['δωμάτιο', 3], ['παλιός', 2], ['εστιατόριο', 4],
  ['βιβλίο', 3], ['ψυγείο', 3], ['διαβάζω', 3],
]) eq(countSyllables(word), n, `слогов в ${word}`);

console.log('Перенос ударения на слог вперёд');
eq(shiftAccentForward('άνθρωπου'), 'ανθρώπου', 'άνθρωπου → ανθρώπου');
eq(shiftAccentForward('πρόσωπου'), 'προσώπου', 'πρόσωπου → προσώπου');

// ─── Склонение ────────────────────────────────────────────────────────────
console.log('Склонение существительных');
// [артикль, им.ед, род.ед, вин.ед, зв.ед, им.мн, род.мн, вин.мн]
for (const [art, nomSg, genSg, accSg, vocSg, nomPl, genPl, accPl] of [
  ['ο', 'άνθρωπος', 'ανθρώπου', 'άνθρωπο', 'άνθρωπε', 'άνθρωποι', 'ανθρώπων', 'ανθρώπους'],
  ['ο', 'δρόμος', 'δρόμου', 'δρόμο', 'δρόμε', 'δρόμοι', 'δρόμων', 'δρόμους'],
  ['ο', 'λογαριασμός', 'λογαριασμού', 'λογαριασμό', 'λογαριασμέ', 'λογαριασμοί', 'λογαριασμών', 'λογαριασμούς'],
  ['ο', 'καφές', 'καφέ', 'καφέ', 'καφέ', 'καφέδες', 'καφέδων', 'καφέδες'],
  ['ο', 'άντρας', 'άντρα', 'άντρα', 'άντρα', 'άντρες', 'αντρών', 'άντρες'],
  ['ο', 'πατέρας', 'πατέρα', 'πατέρα', 'πατέρα', 'πατέρες', null, 'πατέρες'],
  ['ο', 'μαθητής', 'μαθητή', 'μαθητή', 'μαθητή', 'μαθητές', 'μαθητών', 'μαθητές'],
  ['η', 'πόρτα', 'πόρτας', 'πόρτα', 'πόρτα', 'πόρτες', null, 'πόρτες'],
  ['η', 'καρδιά', 'καρδιάς', 'καρδιά', 'καρδιά', 'καρδιές', 'καρδιών', 'καρδιές'],
  ['η', 'ζωή', 'ζωής', 'ζωή', 'ζωή', 'ζωές', 'ζωών', 'ζωές'],
  ['το', 'σπίτι', 'σπιτιού', 'σπίτι', 'σπίτι', 'σπίτια', 'σπιτιών', 'σπίτια'],
  ['το', 'κλειδί', 'κλειδιού', 'κλειδί', 'κλειδί', 'κλειδιά', 'κλειδιών', 'κλειδιά'],
  ['το', 'παράθυρο', 'παραθύρου', 'παράθυρο', 'παράθυρο', 'παράθυρα', 'παραθύρων', 'παράθυρα'],
  ['το', 'πιάτο', 'πιάτου', 'πιάτο', 'πιάτο', 'πιάτα', 'πιάτων', 'πιάτα'],
  ['το', 'δωμάτιο', 'δωματίου', 'δωμάτιο', 'δωμάτιο', 'δωμάτια', 'δωματίων', 'δωμάτια'],
  ['το', 'βιβλίο', 'βιβλίου', 'βιβλίο', 'βιβλίο', 'βιβλία', 'βιβλίων', 'βιβλία'],
  ['το', 'ψυγείο', 'ψυγείου', 'ψυγείο', 'ψυγείο', 'ψυγεία', 'ψυγείων', 'ψυγεία'],
  ['το', 'μάθημα', 'μαθήματος', 'μάθημα', 'μάθημα', 'μαθήματα', 'μαθημάτων', 'μαθήματα'],
  ['το', 'νερό', 'νερού', 'νερό', 'νερό', 'νερά', 'νερών', 'νερά'],
  // Женский род на -ος склоняется как мужской, различаются только артикли
  ['η', 'οδός', 'οδού', 'οδό', 'οδός', 'οδοί', 'οδών', 'οδούς'],
  ['η', 'λεωφόρος', 'λεωφόρου', 'λεωφόρο', 'λεωφόρος', 'λεωφόροι', 'λεωφόρων', 'λεωφόρους'],
  ['η', 'μέθοδος', 'μεθόδου', 'μέθοδο', 'μέθοδος', 'μέθοδοι', 'μεθόδων', 'μεθόδους'],
]) {
  const r = declineNoun(nomSg, art);
  if (!r.table) { failed++; console.error(`  ✗ ${art} ${nomSg}: отказ — ${r.skip}`); continue; }
  const t = r.table;
  eq(t.nom[0], nomSg, `${nomSg} им.ед`);
  eq(t.gen[0], genSg, `${nomSg} род.ед`);
  eq(t.acc[0], accSg, `${nomSg} вин.ед`);
  eq(t.voc[0], vocSg, `${nomSg} зв.ед`);
  eq(t.nom[1], nomPl, `${nomSg} им.мн`);
  eq(String(t.gen[1]), String(genPl), `${nomSg} род.мн`);
  eq(t.acc[1], accPl, `${nomSg} вин.мн`);
}

console.log('Конечное -ν артикля «την»');
for (const [w, art] of [
  // сохраняется перед гласной и перед κ, π, τ, ξ, ψ, μπ, ντ, γκ, τσ, τζ
  ['αγορά', 'την'], ['εκκλησία', 'την'], ['πόρτα', 'την'], ['καρέκλα', 'την'],
  ['τάξη', 'την'], ['ξύστρα', 'την'], ['ψυχή', 'την'], ['μπανάνα', 'την'],
  ['ντομάτα', 'την'], ['τσάντα', 'την'],
  // отпадает перед остальными согласными
  ['μέρα', 'τη'], ['νύχτα', 'τη'], ['φίλη', 'τη'], ['χήρα', 'τη'],
  ['γυναίκα', 'τη'], ['δουλειά', 'τη'], ['ζέστη', 'τη'], ['θάλασσα', 'τη'],
  ['λέξη', 'τη'], ['ρόδα', 'τη'], ['σαλάτα', 'τη'], ['βόλτα', 'τη'],
]) eq(feminineAccusativeArticle(w), art, `${art} ${w}`);

console.log('В слове ровно один тонос');
for (const [art, w] of [['το', 'μάθημα'], ['ο', 'άντρας'], ['ο', 'άνθρωπος'], ['το', 'δωμάτιο']]) {
  const t = declineNoun(w, art).table;
  for (const [c, pair] of Object.entries(t)) {
    for (const form of pair) {
      if (!form) continue;
      const n = [...form].filter((ch) => 'άέήίόύώΐΰ'.includes(ch)).length;
      eq(String(n), '1', `${w} ${c}: «${form}» — тоносов ${n}`);
    }
  }
}

console.log(`\n${passed} проверок пройдено, ${failed} провалено`);
process.exit(failed ? 1 : 0);
